function configuredLanguage(vscode) {
  if (vscode?.env?.language) return vscode.env.language
  try { return JSON.parse(process.env.VSCODE_NLS_CONFIG || '{}').locale || 'en' } catch { return 'en' }
}

function localize(vscode, key, values = {}) {
  const language = configuredLanguage(vscode).toLowerCase().startsWith('zh') ? 'zh' : 'en'
  return messages[language][key].replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''))
}

module.exports = { configuredLanguage, localize }
